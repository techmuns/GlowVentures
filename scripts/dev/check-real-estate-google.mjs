import fs from "node:fs/promises";
import path from "node:path";
import assert from "node:assert/strict";
import { chromium } from "playwright-core";
import { onRequest } from "../../functions/api/real-estate.js";
import { memoryStore } from "./real-estate-fixtures.mjs";
import { installGoogleMapsFixture } from "./google-maps-fixture.mjs";
const base = process.env.BASE || "http://127.0.0.1:4173";
if (!/^http:\/\/(127\.0\.0\.1|localhost)(:\d+)?\/?$/.test(base)) throw new Error("This check writes local test records; use a localhost BASE.");
const out = path.resolve(".cache/real-estate-check/google"); await fs.mkdir(out, { recursive: true });
const store = memoryStore();
const browser = await chromium.launch({ executablePath: process.env.CHROME || "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1512, height: 982 } });
const errors = []; page.on("pageerror", error => errors.push(error.stack || error.message));
let scriptLoads = 0;
await page.route("https://maps.googleapis.com/**", route => {
  scriptLoads++;
  return route.fulfill({ contentType: "application/javascript", body: `(${installGoogleMapsFixture.toString()})();window.__glowMapsReady();` });
});
await page.route("**/api/**", async route => {
  const r = route.request(), pathname = new URL(r.url()).pathname;
  if (pathname === "/api/property-map-config") return route.fulfill({ json: { enabled: true, apiKey: "browser-test-key", mapId: "test-map-id" } });
  if (pathname === "/api/real-estate") {
    const response = await onRequest({ request: new Request(r.url(), { method: r.method(), headers: { ...r.headers(), origin: new URL(base).origin }, ...(r.method() === "POST" ? { body: r.postData() } : {}) }), env: { DASHBOARD_STORE: store } });
    return route.fulfill({ status: response.status, headers: Object.fromEntries(response.headers), body: await response.text() });
  }
  return route.fulfill({ status: 503, json: { ok: false, message: "External feeds disabled for local check." } });
});
const fill = (label, value) => page.getByLabel(label, { exact: true }).fill(value);
const find = () => page.getByRole("button", { name: "Find on map", exact: true }).click();
const message = text => page.getByText(text, { exact: true }).waitFor();
const marker = () => page.locator('[data-property-marker="Drag pin to the property"]');
const saved = () => JSON.parse([...store.data.values()][0]);
try {
  await page.goto(`${base}/real-estate`);
  await page.getByRole("button", { name: "Add property", exact: true }).first().click();
  await fill("Property name *", "Test Google property"); await fill("Owner 1", "Test owner");
  assert.equal(await page.getByLabel("Latitude", { exact: true }).count(), 0);
  assert.equal(await page.getByLabel("Longitude", { exact: true }).count(), 0);
  await fill("Address / survey no. *", "Test no match"); await find();
  await message("No address found. Add a nearby landmark or place the pin on the map.");
  assert.equal(await marker().count(), 0, "No match must not invent a pin.");
  await fill("Address / survey no. *", "Test fail"); await find();
  await message("Address search is unavailable. Try again or place the pin on the map.");
  await fill("Address / survey no. *", "Test ambiguous"); await find();
  await page.getByLabel("Matching addresses").getByRole("button", { name: /Test address B/ }).click();
  await message("Approximate match. Drag the pin to the exact property.");
  assert.equal(await page.getByLabel("City / district *", { exact: true }).inputValue(), "Mumbai");
  assert.equal(await page.getByLabel("State", { exact: true }).inputValue(), "Maharashtra");
  assert.equal(await page.getByLabel("PIN / postal code", { exact: true }).inputValue(), "400001");
  await marker().waitFor();
  assert.equal(await page.locator("[data-google-map-fixture]").getAttribute("data-map-zoom"), "17", "The first address result must zoom to the property, even when it lies inside the initial India view.");
  const rect = await marker().boundingBox(); assert.ok(rect);
  await page.mouse.move(rect.x + 14, rect.y + 14); await page.mouse.down();
  await page.mouse.move(rect.x + 64, rect.y - 16, { steps: 6 }); await page.mouse.up();
  await message("Pin set. Drag it to adjust the exact spot.");
  await page.getByRole("button", { name: "Save property", exact: true }).click();
  await page.getByRole("button", { name: "Edit property", exact: true }).waitFor();
  assert.ok(Math.abs(saved().latitude - 19.079) < 0.000001, "Dragged latitude must be persisted.");
  assert.ok(Math.abs(saved().longitude - 72.8827) < 0.000001, "Dragged longitude must be persisted.");
  const precise = { latitude: saved().latitude, longitude: saved().longitude };
  await page.getByRole("button", { name: "Close property", exact: true }).click(); await page.reload();
  await page.getByRole("button", { name: "Test Google property", exact: true }).click();
  await page.getByRole("button", { name: "Edit property", exact: true }).click();
  await page.getByRole("button", { name: "Adjust pin", exact: true }).click();
  await marker().waitFor();
  assert.equal(await page.evaluate(() => window.__mapsFixture.requests.length), 0, "Opening a saved pin must not geocode it again.");
  await fill("Address / survey no. *", "Test wait old"); await find();
  await page.waitForFunction(() => window.__mapsFixture.pending.length === 1);
  await fill("Address / survey no. *", "Test current");
  await page.evaluate(() => window.__mapsFixture.pending.shift()());
  await page.getByRole("button", { name: "Find on map", exact: true }).waitFor();
  await page.getByRole("button", { name: "Save property", exact: true }).click();
  await page.getByRole("button", { name: "Edit property", exact: true }).waitFor();
  assert.deepEqual({ latitude: saved().latitude, longitude: saved().longitude }, precise, "An old search cannot overwrite a manually positioned pin.");
  await page.getByRole("button", { name: "Edit property", exact: true }).click();
  await find(); await message("Address found. Check the pin and drag it if needed.");
  await page.screenshot({ path: path.join(out, "address-editor.png"), fullPage: true });
  await page.getByRole("button", { name: "Clear pin", exact: true }).click();
  assert.equal(await marker().count(), 0);
  await page.getByLabel("Click map or drag pin to set property location", { exact: true }).click({ position: { x: 200, y: 120 } });
  await message("Pin set. Drag it to adjust the exact spot.");
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  assert.deepEqual({ latitude: saved().latitude, longitude: saved().longitude }, precise, "Cancel must preserve the stored pin.");
  assert.equal(scriptLoads, 2, "Maps script loads once per page, across map/dialog switches.");
  assert.deepEqual(errors, []);
  console.log("Google Maps boundary check passed: address-only entry, no match/error, choices, approximate warning, drag/save/reload, stale search, clear/click/cancel. No Google service or production writes used.");
} catch (error) {
  await page.screenshot({ path: path.join(out, "failure.png"), fullPage: true }).catch(() => {});
  await fs.writeFile(path.join(out, "failure.txt"), `${error.stack ?? error}\n\n${await page.locator("body").innerText().catch(() => "")}`);
  throw error;
} finally { await browser.close(); }
