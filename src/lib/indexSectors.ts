// ── AN INDEX'S SECTOR WEIGHTS, IN THE BOOK'S OWN SECTORS ────────────────────
//
// *"they should be able to select the index in comparison to which they want
// to compare their portfolio sector allocation … just how there is an option
// to compare nav of the portfolio with the indexes performance."*
//
// THE SAME INDICES AS THE NAV CHART, BY THE SAME KEY. `BENCHMARKS` is the one
// list of indices this app sets the book against; Sector Composition offers
// exactly those, so "Nifty Midcap 150" means one index on both tabs.
//
// THE WEIGHTS ARE THE PUBLISHER'S. `src/data/indexSectors.json` is generated by
// `npm run build-index-sectors` from each index's own NSE factsheet — the
// "Sector Representation" table, label and weight as printed, with its date —
// and is never hand-edited (see that script for how it is read and checked).
//
// ONE MAP PLACES BOTH SIDES. NSE prints its own sector names ("Capital Goods",
// "Fast Moving Consumer Goods"); the book's sectors are GICS. Every NSE name is
// resolved through `resolveSector` — the map a PMS fact sheet's or a fund
// filing's sector already goes through — so a sector on the family's side and
// the same sector on the index's side were placed by one definition, never by a
// second table written for this comparison. A name the map cannot place to ONE
// GICS sector ("Diversified", NSE's conglomerates) is the index's own
// Unclassified, at its weight, and named.
//
// THE BSE INDICES CARRY NO WEIGHTS. BSE Index Services publishes which sector
// each Sensex and BSE 500 constituent is in, but no sector weight a run can
// read; the tables that circulate elsewhere weight by full market
// capitalisation, which is not how either index is weighted. So those two are
// never filled from a figure that is not the index's own: `indexSectors()`
// answers them with the reason, and Sector Composition does not offer them
// (Stage 10fo).
import data from "@/data/indexSectors.json";
import { resolveSector, UNCLASSIFIED } from "@/lib/sectors";
import { BENCHMARKS, type Benchmark, type BenchmarkKey } from "@/lib/benchmarks";

type RawIndex = {
  name: string; publisher: string; url: string; asOf: string;
  constituents: number | null; methodology: string | null;
  sectors: { label: string; weight: number }[];
};
const RAW = (data as { indices: Partial<Record<BenchmarkKey, RawIndex>> }).indices;

/** One GICS sector of an index: its weight (a fraction) and the NSE sectors behind it. */
export type IndexSectorRow = {
  sector: string;
  weight: number;
  from: { label: string; weight: number }[];
};

export type IndexSectors =
  | {
      ok: true; bench: Benchmark;
      publisher: string; url: string; asOf: string;
      constituents: number | null; methodology: string | null;
      /** Largest first, the index's own Unclassified (if any) last. */
      rows: IndexSectorRow[];
    }
  | { ok: false; bench: Benchmark; reason: string };

const BSE_ABSENT = "BSE Index Services publishes which sector each constituent of this index is in, but no sector "
  + "weights this dashboard can read. The tables published elsewhere weight by full market capitalisation, "
  + "not the index's free-float weights, so none is shown in their place.";

/** The index's sector weights rolled into GICS sectors, or why there are none. */
export function indexSectors(key: BenchmarkKey): IndexSectors {
  const bench = BENCHMARKS.find((b) => b.key === key) ?? BENCHMARKS[0];
  const raw = RAW[bench.key];
  if (!raw) {
    return { ok: false, bench, reason: bench.key === "sensex" || bench.key === "bse-500" ? BSE_ABSENT
      : `No factsheet for ${bench.name} has been read — \`npm run build-index-sectors\` reads it.` };
  }
  const m = new Map<string, IndexSectorRow>();
  for (const s of raw.sectors) {
    const { sector } = resolveSector(s.label);
    const row = m.get(sector) ?? { sector, weight: 0, from: [] };
    row.weight += s.weight / 100;
    row.from.push(s);
    m.set(sector, row);
  }
  const rows = [...m.values()].sort((a, b) =>
    (a.sector === UNCLASSIFIED ? 1 : 0) - (b.sector === UNCLASSIFIED ? 1 : 0) || b.weight - a.weight);
  return {
    ok: true, bench, publisher: raw.publisher, url: raw.url, asOf: raw.asOf,
    constituents: raw.constituents, methodology: raw.methodology, rows,
  };
}

/** What a GICS sector of an index is made of, in the factsheet's own words — a cell's hover. */
export function indexSectorFrom(row: IndexSectorRow): string {
  return row.from.map((f) => `${f.label} ${f.weight.toFixed(2)}%`).join(" + ");
}
